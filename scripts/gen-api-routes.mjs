// api/*.ts (언더스코어로 시작하는 파일 제외) 를 스캔해 api/_generated/routes.ts 를 생성한다.
// 파일명이 곧 라우트 이름이다: api/hello.ts → GET {VITE_API_URL}/hello
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const apiDir = join(dirname(fileURLToPath(import.meta.url)), "..", "api");
const outDir = join(apiDir, "_generated");

const names = readdirSync(apiDir)
  .filter((f) => f.endsWith(".ts") && !f.startsWith("_") && !f.endsWith(".d.ts"))
  .map((f) => f.slice(0, -3))
  .sort();

for (const name of names) {
  if (!/^[a-z0-9-]+$/.test(name)) {
    throw new Error(`api/${name}.ts: route file names must be kebab-case`);
  }
}

const ident = (name) => `route_${name.replace(/-/g, "_")}`;
const source = [
  "// AUTO-GENERATED by scripts/gen-api-routes.mjs — do not edit.",
  'import type { RouteMap } from "../_lib/http";',
  ...names.map((n) => `import ${ident(n)} from "../${n}";`),
  "",
  "export const routes: RouteMap = {",
  ...names.map((n) => `  "${n}": ${ident(n)},`),
  "};",
  "",
].join("\n");

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "routes.ts"), source);
console.log(`Generated ${names.length} API route(s): ${names.join(", ") || "(none)"}`);
